const sec = (n: number | undefined) => (n ? `${Math.round(n)} ث` : "");
const short = (xs: string[] | undefined, n = 1, max = 120) => (xs ?? []).slice(0, n).map((x) => (x.length > max ? `${x.slice(0, max - 1)}…` : x)).join(" ");

/** Shots without the hook duplicated or an empty closing row. */
export function shotRows(s: Scenario): { label: string; spoken: string; visual: string; on_screen_text: string; seconds: number }[] {
  const rows = [{ label: "الافتتاحية", ...s.hook }, ...s.sections];
  const seen = new Set<string>();
  const out = rows.filter((r) => { const k = (r.spoken ?? "").trim().slice(0, 40); if (!k) return Boolean(r.visual); if (seen.has(k)) return false; seen.add(k); return true; });
  if ((s.cta.spoken ?? "").trim() || (s.cta.on_screen_text ?? "").trim()) out.push({ label: "الخاتمة", spoken: s.cta.spoken, visual: "", on_screen_text: s.cta.on_screen_text, seconds: 0 });
  return out;
}

/** The checks the producing tool must pass before delivering. This is what controls quality, not longer prose. */
export function acceptanceChecks(s: Scenario): string[] {
  const st = s.style;
  const climax = s.arc?.find((a) => /ذروة/.test(a.stage));
  const climaxAt = climax ? s.arc.slice(0, s.arc.indexOf(climax)).reduce((t, a) => t + (a.seconds || 0), 0) : null;
  return [
    `المدة النهائية ${Math.round(s.duration_sec)} ث ± ٢ ث.`,
    `السكربت يُقرأ حرفيًا: لا حذف ولا إضافة ولا تغيير في الأسماء والأرقام.`,
    st?.dialect ? `التعليق الصوتي بلهجة «${st.dialect}»، صوت رجالي واثق، بلا أسلوب نشرات.` : `التعليق الصوتي بلهجة الاستنساخ، صوت رجالي واثق.`,
    `الافتتاحية: كلام ونص على الشاشة معًا في الثانية الأولى، بلا تحية.${climaxAt != null ? ` ذروة واحدة عند الثانية ${Math.round(climaxAt)} تقريبًا.` : ""}`,
    `لكل لقطة بطل بصري واحد، والنص على الشاشة داخل المساحات الآمنة ومتزامن مع الكلام.`,
    /موسيقى|إيقاع|drone|beat/i.test(s.music) && !/لا موسيقى|بلا موسيقى|صمت|0%|لا توجد/.test(s.music) ? `إن وُجدت موسيقى فهي Instrumental بلا أي صوت بشري وتنخفض مع الكلام.` : `الصوت كما في توجيه الموسيقى: التعليق الصوتي وحده، والمؤثرات مربوطة بأحداث بصرية.`,
    st?.never_uses.length ? `ممنوع: ${st.never_uses.map((x) => x.replace(/[.؛،\s]+$/u, "")).join("؛ ")}.` : ``,
    `التسليم: الفيديو النهائي، الغلاف، السكربت والمصادر، ملفات المشروع.`,
  ].filter(Boolean);
}

/**
 * The job card: everything that changes per scenario, and nothing else. Topic and specs, five style lines,
 * the script once, the arc, the shot list (visual + on-screen only; the words are in the script), sound, checks.
 */
export function buildJobCard(s: Scenario, opts: { topic?: string; creator?: string } = {}): string {
  const st = s.style;
  const rows = shotRows(s);
  return [
    `بطاقة عمل · ${opts.topic ?? s.title}`,
    `المقاس 9:16 · 1080×1920 · المدة ${Math.round(s.duration_sec)} ث${st?.dialect ? ` · اللهجة: ${st.dialect}` : ""}${opts.creator ? ` · بأسلوب «${opts.creator}»` : ""}`,
    st ? `الأسلوب: ${st.one_line}` : "",
    st?.speech.length ? `الإلقاء: ${short(st.speech)}` : "",
    st?.opening.length ? `الافتتاحية: ${short(st.opening)}` : "",
    st?.visuals.length ? `المرئيات: ${short(st.visuals)}` : "",
    st?.music.length ? `الصوت: ${short(st.music)}` : "",
    st?.structure.length ? `البنية: ${short(st.structure)}` : "",
    ``,
    `السكربت (يُقرأ كما هو):`,
    s.script,
    ``,
    s.arc?.length ? `المنحنى: ${s.arc.map((a) => `${a.stage} ${sec(a.seconds)}${a.goal ? ` (${a.goal.length > 60 ? `${a.goal.slice(0, 59)}…` : a.goal})` : ""}`).join(" ← ")}` : "",
    ``,
    `اللقطات:`,
    ...rows.map((r, i) => `${i + 1}. ${r.label}${r.seconds ? ` · ${sec(r.seconds)}` : ""} · ${r.visual ? (r.visual.length > 140 ? `${r.visual.slice(0, 139)}…` : r.visual) : "—"}${r.on_screen_text ? ` · «${r.on_screen_text}»` : ""}`),
    ``,
    `الموسيقى: ${s.music}`,
    s.notes ? `ملاحظات: ${s.notes.length > 160 ? `${s.notes.slice(0, 159)}…` : s.notes}` : "",
    ``,
    `شروط القبول:`,
    ...acceptanceChecks(s).map((c) => `- ${c}`),
  ].filter((l) => l !== "").join("\n");
}

/** Rules + job card in one text, for a tool that has no standing instructions. */
export function buildVideoBrief(s: Scenario, opts: { topic?: string; creator?: string } = {}): string {
  return `${VIDEO_DIRECTOR_RULES}\n\n────────────────────────\n${buildJobCard(s, opts)}`;
}
