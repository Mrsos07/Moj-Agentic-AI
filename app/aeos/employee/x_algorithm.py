"""
x_algorithm — دليل خوارزمية X المدمج في عقل كل موظف ذكي.

معرفة مقطّرة من الكود المفتوح لخوارزمية X (heavy ranker + SimClusters/TwHIN،
مستودع twitter/the-algorithm) ومن ممارسات النمو المثبتة، محوّلة إلى:

1. ``algo_prompt_block(kind)``  — كتلة توجيه عربية مدمجة تُحقن في برومبت توليد
   المحتوى/الرد/الاقتباس/الثريد، مفصّلة حسب نوع الإجراء. ثابتة وحتمية
   (بلا LLM) فلا تكلّف شيئاً ولا تتغير بين دورة وأخرى إلا بمقدار ما يريده
   التناوب المتعمد.
2. ``virality_findings(texts)`` — فحوصات حتمية بعد النشر تُغذّي نقد الدورة
   (critique) بمخالفات الخوارزمية المقيسة بالأرقام، فتتحوّل إلى توجيهات
   تصحيحية في الدورة التالية.

أهم أوزان الترتيب (نموذج الترتيب الثقيل المفتوح المصدر — نسب تقريبية
معيّرة على الإعجاب = 1):
- ردّ يفتح محادثة يواصل صاحبها التفاعل فيها  ≈ 150x
- ردّ على منشورك (conversation)               ≈ 27x
- زيارة بروفايل + تفاعل                        ≈ 24x
- إعادة نشر                                    ≈ 2x
- إعجاب                                        = 1x
- مشاهدة فيديو >50%                            ≈ 0.01x
- إشارات سلبية (بلاغ/كتم/حجب/«اعرض أقل»)      ≈ سالب مئات الأضعاف

الاستنتاجات المدمجة في التوجيه:
- الردود أثمن عملة: محتوى يستدرج ردوداً حقيقية > محتوى يُعجب الناس بصمت.
- الرد على من ردّ عليك (conversation depth) أقوى مضخّم انتشار متاح مجاناً.
- الروابط الخارجية في متن التغريدة تخفض الوصول — تُوضع في ردّ ذاتي.
- أكثر من هاشتاق واحد = إشارة سبام. الوسوم للمشاركة في ترند لا للتزيين.
- أول 30-60 دقيقة تحدد الانتشار خارج المتابعين (SimClusters) — لذا النشر
  في ساعات الجمهور المقيسة والرد السريع على أوائل المتفاعلين حاسمان.
- الهوية الموضوعية الثابتة (المحاور) تحسّن تصنيف الحساب في عناقيد
  الاهتمام فيصل المحتوى لجمهور المجال خارج المتابعين.
- الإشارات السلبية أغلى من كل الإيجابيات: الإثارة الرخيصة خارج التخصص
  تربح دورة وتدفن الحساب شهراً.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

ALGO_VERSION = 1

_URL_RE = re.compile(r"https?://\S+")
_HASHTAG_RE = re.compile(r"#\S+")
_EMOJI_RE = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F000-\U0001F02F"
    "\U0001F900-\U0001F9FF\U00002190-\U000021FF\U00002B00-\U00002BFF]"
)
#: أسئلة قالبية لا تفتح نقاشاً حقيقياً — وجودها وحده لا يُحتسب «محفّز ردود»
_GENERIC_CTA = ("ما رأيكم", "ما رايكم", "شاركونا", "ما تعليقكم", "برأيكم",
                "what do you think", "thoughts?")

# ──────────────────────── كتل التوجيه لكل نوع إجراء ────────────────────────
_COMMON = [
    "الردود أثمن إشارة ترتيب على X (تفوق الإعجاب بعشرات الأضعاف): اكتب "
    "بزاوية تستدرج رداً حقيقياً — موقف قابل للاعتراض المحترم، سؤال محدّد "
    "يملك القارئ إجابة عنه، أو معلومة تدفع للإضافة. ممنوع أسئلة القوالب "
    "«ما رأيكم/شاركونا» فهي لا تستدرج أحداً.",
    "ممنوع وضع أي رابط خارجي في متن المنشور — الخوارزمية تخفض وصوله. "
    "إن كان لا بد من مصدر فاذكره اسماً («وفق رويترز») بلا رابط.",
    "الإشارات السلبية (بلاغ/كتم/«اعرض أقل») تسحق الحساب: لا إثارة رخيصة، "
    "لا تهويل بلا دليل، ولا خوض في مواضيع خلافية خارج تخصصك.",
]

_BY_KIND: Dict[str, List[str]] = {
    "post": [
        "اجعل المنشور «يستحق الحفظ أو المشاركة»: رقم/حقيقة/خلاصة عملية "
        "يريد القارئ الرجوع إليها — الحفظ والمشاركة إشارتا ترتيب قويتان.",
    ],
    "thread": [
        "التغريدة الأولى تقرر مصير الثريد كله: خطّاف يعد بقيمة محدّدة "
        "قابلة للقياس («7 أخطاء…»، «القصة الكاملة لـ…») بلا مبالغة.",
        "الثريد يرفع زمن البقاء (dwell time) وهو إشارة ترتيب — كل تغريدة "
        "تعطي سبباً للاستمرار للتي بعدها، والأخيرة تفتح نقاشاً.",
    ],
    "reply": [
        "ردّك على منشور غيرك يظهر لجمهوره أنت لا يعرفك: أضف قيمة تجعل "
        "قارئه يزور بروفايلك (معلومة تكمّل، تصحيح مهذّب بدليل، زاوية "
        "لم يرها صاحب المنشور) — زيارة البروفايل بعد الرد إشارة ترتيب قوية.",
        "لا تردّ رداً عاماً يصلح لأي تغريدة؛ الرد الفارغ يُقرأ كسبام.",
    ],
    "quote": [
        "الاقتباس يبني صوتك على جمهور غيرك: خذ موقفاً واضحاً من المقتبَس "
        "(أكمل نقصه، أو عارضه بدليل) — الاقتباس المحايد «صحيح، مهم» لا "
        "يضيف شيئاً ولا ينتشر.",
    ],
}


def algo_prompt_block(kind: str = "post",
                      best_hours: Optional[List[int]] = None,
                      include_common: bool = True) -> str:
    """كتلة «قواعد خوارزمية X» تُلحق ببرومبت التوليد حسب نوع الإجراء.

    ``kind``: post | thread | reply | quote — غير المعروف يُعامل كـ post.
    ``best_hours``: ساعات النشر الأنجح المقيسة من أداء الحساب نفسه (اختياري،
    تُذكر للنموذج كسياق لا كأمر لأن توقيت التنفيذ بيد المجدول لا النموذج).
    ``include_common=False``: أضِف قواعد النوع فقط — لبرومبت الثريد الذي
    يمرّ عبر برومبت المنشور فتكون القواعد المشتركة موجودة أصلاً.
    """
    lines = ["[قواعد خوارزمية X — مدمجة، التزم بها حرفياً]"]
    if include_common:
        lines += _COMMON
    lines += _BY_KIND.get(kind, _BY_KIND["post"])
    if best_hours:
        hrs = "، ".join(f"{int(h)}:00" for h in best_hours[:3])
        lines.append(f"جمهورك الأنشط قياساً في الساعات (UTC): {hrs} — "
                     "المنشور المنشور قرب هذه الساعات يكسب دفعة الانطلاق الأولى.")
    return "\n".join(f"- {l}" if not l.startswith("[") else l for l in lines)


# ─────────────────────── فحوصات حتمية بعد النشر ───────────────────────
def virality_findings(texts: List[str]) -> List[Dict[str, str]]:
    """مخالفات الخوارزمية في نصوص نُشرت فعلاً — بلا LLM، أرقام فقط.

    كل عنصر: ``{key, problem, directive}`` بنفس عقد
    ``critique._rule_based_issues`` فيندمج في نقد الدورة مباشرة.
    """
    issues: List[Dict[str, str]] = []
    joined = " ".join(t for t in texts if t)
    if not joined.strip():
        return issues

    if _URL_RE.search(joined):
        issues.append({
            "key": "external_link_in_post",
            "problem": "وضعت رابطاً خارجياً في متن المنشور",
            "directive": "الخوارزمية تخفض وصول التغريدات ذات الروابط: اذكر "
                         "المصدر اسماً في المتن، وضع الرابط في ردّ ذاتي إن لزم.",
        })
    emojis = len(_EMOJI_RE.findall(joined))
    if emojis > 2 * max(1, len(texts)):
        issues.append({
            "key": "emoji_overload",
            "problem": f"استخدمت {emojis} إيموجي",
            "directive": "إيموجي واحد كحد أقصى للتغريدة — الحشو يُقرأ كسبام "
                         "ويضعف جدية المحتوى.",
        })
    low = joined.lower()
    if any(c in low for c in _GENERIC_CTA):
        issues.append({
            "key": "generic_cta",
            "problem": "استخدمت سؤال قالب عام («ما رأيكم/شاركونا»)",
            "directive": "استدرج الردود بموقف قابل للاعتراض أو سؤال محدّد "
                         "يملك القارئ إجابة شخصية عنه، لا بسؤال قالبي.",
        })
    # نمط أحادي: كل النصوص تنتهي بسؤال — أظهر ما يجعل الحساب يبدو آلياً
    real = [t.strip() for t in texts if t and t.strip()]
    if len(real) >= 2:
        ending_q = sum(1 for t in real if t.endswith(("?", "؟")))
        if ending_q == len(real):
            issues.append({
                "key": "question_ending_every_text",
                "problem": f"كل النصوص ({len(real)}) انتهت بسؤال",
                "directive": "غيّر الخواتيم: اختم أغلب النصوص بجملة موقف أو "
                             "خلاصة ملموسة، والسؤال نمط واحد من عدّة لا قاعدة.",
            })
        openings = {" ".join(t.split()[:3]).lower() for t in real}
        if len(real) >= 3 and len(openings) == 1:
            issues.append({
                "key": "monotone_openings",
                "problem": "كل النصوص بدأت بالمطلع نفسه",
                "directive": "نوّع المطالع والنبرة بين المنشورات (رقم، مفارقة، "
                             "مشهد، تصحيح اعتقاد) بدل قالب واحد متكرر.",
            })
    return issues
